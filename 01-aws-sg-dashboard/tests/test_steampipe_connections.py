import re

import pytest
import extract_and_visualize_v2 as m


class TestSteampipeConnectionName:

    @pytest.mark.parametrize('profile,expected', [
        ('prod', 'aws_prod'),
        ('lbox-system', 'aws_lbox_system'),
        ('Prod Admin', 'aws_prod_admin'),
        ('team.dev', 'aws_team_dev'),
    ])
    def test_name_is_valid_schema(self, profile, expected):
        assert m.steampipe_connection_name(profile) == expected

    def test_collision_aborts(self):
        with pytest.raises(SystemExit) as exc:
            m.steampipe_connection_map(['a-b', 'a_b'])
        assert exc.value.code == 1


class TestAggregatorConfig:

    def test_config_uses_valid_connection_names(self, tmp_path, monkeypatch):
        path = tmp_path / 'aws.spc'
        monkeypatch.setattr(m, 'STEAMPIPE_CONFIG_PATH', str(path))

        m.setup_aggregator_config(['lbox-system', 'prod'], regions=['ap-northeast-2'])

        content = path.read_text()
        names = re.findall(r'connection "([^"]+)"', content)
        assert names == ['aws_lbox_system', 'aws_prod', 'aws']
        # The AWS profile itself keeps its original name
        assert 'profile = "lbox-system"' in content


class TestAccountIdentities:

    def test_connection_maps_back_to_original_profile(self, monkeypatch):
        monkeypatch.setattr(m, 'run_steampipe_query', lambda q: {'rows': [
            {'account_id': '111', 'account_aliases': [], 'connection_name': 'aws_lbox_system'},
            {'account_id': '222', 'account_aliases': ['legacy'], 'connection_name': 'aws_legacy'},
        ]})

        accounts = m.get_all_account_identities(['lbox-system'])

        assert accounts['111']['profile_name'] == 'lbox-system'
        # Connection not generated by this script (e.g. --skip-config): prefix stripped
        assert accounts['222']['profile_name'] == 'legacy'
